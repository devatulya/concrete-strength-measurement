export async function predictConcreteStrength(mix: ConcreteMixInput): Promise<PredictionResponse> {
  if (!API_BASE) {
    return predictLocal(mix);
  }

  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 3500);

    const resp = await fetch(`${API_BASE}/api/v1/predict`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Accept': 'application/json'
      },
      body: JSON.stringify(mix),
      signal: controller.signal
    });
    clearTimeout(timeoutId);

    const data = await resp.json();
    if (!resp.ok) {
      // If it is a domain validation error (e.g., negative value or zero binder), throw it so user gets feedback
      if (resp.status === 400 || resp.status === 422) {
        const errorMsg = data.message || data.detail || data.error || `Validation error: HTTP ${resp.status}`;
        throw new Error(errorMsg);
      }
      // If server has a 500/503 error, fallback to embedded client engine
      return predictLocal(mix);
    }
    return data;
  } catch (err: any) {
    // Re-throw genuine client validation errors
    if (err.message && (err.message.includes('greater than zero') || err.message.includes('non-negative') || err.message.includes('Validation error'))) {
      throw err;
    }
    // Network failure or serverless timeout -> seamless fallback to local engine
    return predictLocal(mix);
  }
}

export function generateCSVReport(prediction: PredictionResponse): string {
  const { submitted_mix, calculated_properties, predicted_strength_mpa, model_name, model_version, prediction_timestamp } = prediction;
  
  const rows = [
    ['CONCRETE COMPRESSIVE STRENGTH PREDICTION REPORT', ''],
    ['Generated by Concrete Strength Predictor (B.Tech Civil Engineering Project)', ''],
    ['Timestamp (UTC)', prediction_timestamp],
    ['Model Engine', `${model_name} (v${model_version})`],
    ['', ''],
    ['--- MIX SPECIFICATION (kg/m³) ---', ''],
    ['Cement (OPC)', `${submitted_mix.cement} kg/m³`],
    ['Blast Furnace Slag (GGBS)', `${submitted_mix.slag} kg/m³`],
    ['Fly Ash', `${submitted_mix.fly_ash} kg/m³`],
    ['Batch Water', `${submitted_mix.water} kg/m³`],
    ['Superplasticizer (HRWR)', `${submitted_mix.superplasticizer} kg/m³`],
    ['Coarse Aggregate (~20mm)', `${submitted_mix.coarse_aggregate} kg/m³`],
    ['Fine Aggregate (Sand)', `${submitted_mix.fine_aggregate} kg/m³`],
    ['Curing Age', `${submitted_mix.age} days`],
    ['', ''],
    ['--- MIX CALCULATIONS ---', ''],
    ['Total Cementitious Binder', `${calculated_properties.total_binder_kg_m3} kg/m³`],
    ['Water-to-Binder Ratio (w/b)', calculated_properties.water_to_binder_ratio.toFixed(3)],
    ['Total Aggregate Content', `${calculated_properties.total_aggregate_kg_m3} kg/m³`],
    ['Fine Aggregate Ratio', `${(calculated_properties.fine_to_total_aggregate_ratio * 100).toFixed(1)}%`],
    ['Estimated Fresh Density', `${calculated_properties.estimated_fresh_density_kg_m3} kg/m³`],
    ['', ''],
    ['--- PREDICTION RESULT ---', ''],
    ['Predicted Compressive Strength', `${predicted_strength_mpa} MPa (N/mm²)`],
    ['Equivalent Cylinder / Cube Note', 'Trained on 150mm standard cube benchmark specimens'],
    ['', ''],
    ['--- CIVIL ENGINEERING DISCLAIMER ---', ''],
    ['Notice', 'Output is an empirical machine-learning estimate based on laboratory benchmark data.'],
    ['Limitations', 'Actual strength in field depends on batching, moisture correction, compaction, and curing per IS 516 / ASTM C39.']
  ];

  return rows.map(r => `"${r[0]}","${r[1]}"`).join('\n');
}
