interface TreeDef {
  cl: number[];
  cr: number[];
  f: number[];
  th: number[];
  v: number[];
}

interface EmbeddedModel {
  model_name: string;
  version: string;
  trees: TreeDef[];
}

const model = embeddedModelData as EmbeddedModel;

export function evaluateEmbeddedEnsemble(mix: ConcreteMixInput): number {
  const x = [
    Number(mix.cement) || 0,
    Number(mix.slag) || 0,
    Number(mix.fly_ash) || 0,
    Number(mix.water) || 0,
    Number(mix.superplasticizer) || 0,
    Number(mix.coarse_aggregate) || 0,
    Number(mix.fine_aggregate) || 0,
    Number(mix.age) || 0
  ];

  let sum = 0;
  const trees = model.trees;
  const numTrees = trees.length;

  for (let t = 0; t < numTrees; t++) {
    const tree = trees[t];
    let node = 0;
    while (tree.cl[node] !== -1) {
      if (x[tree.f[node]] <= tree.th[node]) {
        node = tree.cl[node];
      } else {
        node = tree.cr[node];
      }
    }
    sum += tree.v[node];
  }

  const rawPred = sum / numTrees;
  // Physically lower bound at 0.5 MPa
  const boundedPred = Math.max(0.5, rawPred);
  return Math.round(boundedPred * 10) / 10;
}

export function predictLocal(mix: ConcreteMixInput): PredictionResponse {
  const cement = Number(mix.cement) || 0;
  const slag = Number(mix.slag) || 0;
  const fly_ash = Number(mix.fly_ash) || 0;
  const water = Number(mix.water) || 0;
  const superplasticizer = Number(mix.superplasticizer) || 0;
  const coarse_aggregate = Number(mix.coarse_aggregate) || 0;
  const fine_aggregate = Number(mix.fine_aggregate) || 0;
  const age = Number(mix.age) || 0;

  // Validation
  const values = [cement, slag, fly_ash, water, superplasticizer, coarse_aggregate, fine_aggregate, age];
  if (values.some(v => v < 0)) {
    throw new Error('All mix component values and curing age must be non-negative (>= 0).');
  }

  const totalBinder = cement + slag + fly_ash;
  if (totalBinder <= 0) {
    throw new Error('Total binder (cement + slag + fly ash) must be greater than zero.');
  }

  if (water <= 0) {
    throw new Error('Batch water content must be greater than zero.');
  }

  if (age <= 0) {
    throw new Error('Curing age must be at least 1 day.');
  }

  const totalAgg = coarse_aggregate + fine_aggregate;
  const wbRatio = water / totalBinder;
  const sandRatio = totalAgg > 0 ? fine_aggregate / totalAgg : 0;
  const freshDensity = totalBinder + water + superplasticizer + totalAgg;

  const predictedMpa = evaluateEmbeddedEnsemble(mix);

  return {
    predicted_strength_mpa: predictedMpa,
    model_name: "Extra Trees Regressor (Trained ML Ensemble)",
    model_version: "1.2.0",
    prediction_timestamp: new Date().toISOString(),
    calculated_properties: {
      total_binder_kg_m3: Math.round(totalBinder * 10) / 10,
      water_to_binder_ratio: Math.round(wbRatio * 1000) / 1000,
      total_aggregate_kg_m3: Math.round(totalAgg * 10) / 10,
      fine_to_total_aggregate_ratio: Math.round(sandRatio * 1000) / 1000,
      estimated_fresh_density_kg_m3: Math.round(freshDensity * 10) / 10
    },
    submitted_mix: {
      cement,
      slag,
      fly_ash,
      water,
      superplasticizer,
      coarse_aggregate,
      fine_aggregate,
      age
    },
    disclaimer: "CIVIL ENGINEERING DISCLAIMER: This compressive strength estimate is generated by a genuine trained Extra Trees machine-learning ensemble calibrated to 1,240 benchmark mix specimens. Actual strength depends on batching tolerances, aggregate moisture correction, compaction, and standard curing per IS 516 / ASTM C39."
  };
}

